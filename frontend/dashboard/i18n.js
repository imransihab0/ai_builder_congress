let locale = "bn";
const listeners = new Set();

export function getLocale() {
  return locale;
}

export function setLocale(nextLocale) {
  if (!LOCALES.includes(nextLocale)) throw new RangeError(`Unsupported locale: ${nextLocale}`);
  locale = nextLocale;
  applyDocumentLang();
  listeners.forEach((listener) => listener(locale));
  return locale;
}

export function onLocaleChange(listener) {
  if (typeof listener !== "function") throw new TypeError("Locale listener must be a function");
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function t(key, vars = {}) {
  const message = key.split(".").reduce((value, part) => value?.[part], MESSAGES[locale]);
  if (typeof message !== "string") return key;
  return message.replace(/\{(\w+)\}/g, (placeholder, name) =>
    Object.hasOwn(vars, name) ? String(vars[name]) : placeholder,
  );
}

export function fmtNum(number, maxFractionDigits = 0) {
  const options = typeof maxFractionDigits === "object"
    ? maxFractionDigits
    : { maximumFractionDigits: maxFractionDigits };
  return new Intl.NumberFormat(LOCALE_TAGS[locale], options).format(number);
}

export function fmtDate(iso, options) {
  return new Intl.DateTimeFormat(LOCALE_TAGS[locale], options).format(new Date(iso));
}

export function applyDocumentLang() {
  if (typeof document !== "undefined" && document.documentElement) {
    document.documentElement.lang = locale;
  }
  return locale;
}
